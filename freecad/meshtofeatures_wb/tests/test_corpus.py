"""Regression corpus: five synthetic machined parts with analytic ground truth.

Each STL in ``fixtures/`` is generated by ``fixtures/generate_corpus.py``
(exact CSG, known volume and feature set). These tests pin the STABLE,
CORRECT core of the pipeline on each part:

* the mesh still carries the generated volume (guards against a broken
  regeneration of the corpus),
* the feature detector sees the real features with their diameters and
  depths,
* the coverage is at or above the recorded floor,
* the executed plan, after the canonical OVER/UNDER corrections
  (``plan_to_mesh`` + ``plan_corrections`` + ``apply_corrections``),
  reproduces the source mesh within 1% of volume -- the gate the
  generator's docstring promises.

Deliberately NOT asserted: artifact-prone flags (through/blind where the
detector truncates a bore at a countersink) and gap-prone features
(countersink cones on ``block_countersunk``; the Ø10 cross bore on
``cross_holed_block`` that lands in ``unplanned`` as an open slot). Those
are known detection gaps, pinned separately when closed.
"""

from pathlib import Path

import numpy as np
import pytest
import trimesh

pytest.importorskip("manifold3d")

from freecad.meshtofeatures_wb.core.emission import plan_patches
from freecad.meshtofeatures_wb.core.features import detect_features
from freecad.meshtofeatures_wb.core.history import plan_history
from freecad.meshtofeatures_wb.core.patterns import detect_patterns
from freecad.meshtofeatures_wb.core.pipeline import reconstruct
from freecad.meshtofeatures_wb.core.snapping import snap_report
from freecad.meshtofeatures_wb.core.solidify import (
    apply_corrections,
    plan_corrections,
    plan_to_mesh,
)

FIXTURES = Path(__file__).resolve().parent / "fixtures"

# Analytic volume of each corpus part (exact CSG, generate_corpus.py).
EXPECTED_VOLUME = {
    "corpus_block_countersunk.stl": 45324.45,
    "corpus_bossed_plate.stl": 34739.18,
    "corpus_cross_holed_block.stl": 59900.16,
    "corpus_plate_counterbored.stl": 20957.55,
    "corpus_stepped_chamfered.stl": 28131.88,
}

SIZE_TOL = 0.3   # diameter / size / width
DEPTH_TOL = 1.5


def _load(name):
    mesh = trimesh.load(str(FIXTURES / name))
    if isinstance(mesh, trimesh.Scene):
        mesh = mesh.dump(concatenate=True)
    return mesh


def _full(mesh):
    report = snap_report(reconstruct(mesh)).report
    patches = plan_patches(report)
    feats = detect_features(report, patches)
    plan = plan_history(report, feats, detect_patterns(feats), patches)
    return report, feats, plan


def _check_fixture_volume(name, mesh):
    expected = EXPECTED_VOLUME[name]
    got = float(mesh.volume)
    assert abs(got - expected) / expected < 0.01, (
        f"{name}: mesh volume {got:.2f} drifted from analytic {expected:.2f}")


def _gate(mesh, plan):
    """The executed plan must reproduce the source mesh within 1% volume
    after the canonical OVER/UNDER corrections."""
    solid = plan_to_mesh(plan)
    assert solid is not None, "plan could not be executed headlessly"
    corrected = apply_corrections(solid, mesh, plan_corrections(plan, mesh))
    ratio = abs(float(corrected.volume) - float(mesh.volume)) / float(mesh.volume)
    assert ratio < 0.01, f"corrected volume off by {ratio:.2%}"


def _axis_close(axis, ref, tol=0.9):
    a = np.asarray(axis, dtype=float)
    return abs(float(np.dot(a, ref))) / float(np.linalg.norm(a)) > tol


class TestBlockCountersunk:
    """Countersunk bores + one blind Ø12 bore + a pocket. The countersink
    cones are a known detection gap (see module docstring)."""

    def test_corpus_and_core(self):
        name = "corpus_block_countersunk.stl"
        mesh = _load(name)
        _check_fixture_volume(name, mesh)
        report, feats, plan = _full(mesh)
        assert report.coverage >= 0.95
        holes = feats.by_kind("hole")
        assert len(holes) == 3
        diameters = sorted(h.params["diameter"] for h in holes)
        assert np.allclose(diameters, [10, 10, 12], atol=SIZE_TOL)
        deep = max(holes, key=lambda h: h.params["diameter"])
        assert abs(deep.params["depth"] - 8.0) <= DEPTH_TOL, \
            f"Ø12 blind bore depth {deep.params['depth']}, expected 8"
        _gate(mesh, plan)


class TestBossedPlate:
    """Plate with a boss: four Ø6 holes (two through, two to the pocket
    floor) and a 36x10 slot pocket."""

    def test_corpus_and_core(self):
        name = "corpus_bossed_plate.stl"
        mesh = _load(name)
        _check_fixture_volume(name, mesh)
        report, feats, plan = _full(mesh)
        assert report.coverage >= 0.99
        holes = feats.by_kind("hole")
        assert len(holes) == 4
        for h in holes:
            assert abs(h.params["diameter"] - 6.0) <= SIZE_TOL
            assert h.params["through"] is True
        depths = sorted(h.params["depth"] for h in holes)
        assert np.allclose(depths, [8, 8, 20, 20], atol=DEPTH_TOL)
        slots = [p for p in feats.by_kind("pocket")
                 if p.params.get("opening_size")]
        assert len(slots) == 1
        opening = sorted(float(v) for v in slots[0].params["opening_size"])
        assert np.allclose(opening, [10, 36], atol=0.5), \
            f"slot opening {opening}, expected [10, 36]"
        _gate(mesh, plan)


class TestCrossHoledBlock:
    """Block with a Z bore, a blind X bore, and a Ø10 through Y bore. The
    Y bore lands in ``unplanned`` as an open slot (known gap); the X bore
    and the Z cross-hole are pinned."""

    def test_corpus_and_core(self):
        name = "corpus_cross_holed_block.stl"
        mesh = _load(name)
        _check_fixture_volume(name, mesh)
        report, feats, plan = _full(mesh)
        assert report.coverage >= 0.99
        x_bore = [h for h in feats.by_kind("hole")
                  if _axis_close(h.params.get("axis", (1, 0, 0)), (1, 0, 0))]
        assert len(x_bore) == 1, "blind X bore not detected"
        assert abs(x_bore[0].params["diameter"] - 8.0) <= SIZE_TOL
        assert abs(x_bore[0].params["depth"] - 15.0) <= DEPTH_TOL, \
            f"X bore depth {x_bore[0].params['depth']}, expected 15"
        slots = feats.by_kind("slot")
        assert len(slots) == 1, "Y bore not detected as a slot"
        assert abs(slots[0].params["width"] - 10.0) <= SIZE_TOL
        assert slots[0].params["through"] is True
        assert _axis_close(slots[0].params.get("axis", (0, 1, 0)), (0, 1, 0))
        z_bores = [ch for ch in plan.cross_holes
                   if abs(ch.diameter - 8.0) <= SIZE_TOL]
        assert z_bores, "Z bore missing from plan.cross_holes"
        _gate(mesh, plan)


class TestPlateCounterbored:
    """Plate with two plain Ø8 through holes and two Ø8 counterbores
    (Ø14 x 5 deep)."""

    def test_corpus_and_core(self):
        name = "corpus_plate_counterbored.stl"
        mesh = _load(name)
        _check_fixture_volume(name, mesh)
        report, feats, plan = _full(mesh)
        assert report.coverage >= 0.999
        plain = feats.by_kind("hole")
        cbs = feats.by_kind("counterbore")
        assert len(plain) == 2
        assert len(cbs) == 2
        for h in plain:
            assert abs(h.params["diameter"] - 8.0) <= SIZE_TOL
        for c in cbs:
            assert abs(c.params["diameter"] - 8.0) <= SIZE_TOL
            assert abs(c.params["counterbore_diameter"] - 14.0) <= SIZE_TOL
            assert abs(c.params["counterbore_depth"] - 5.0) <= DEPTH_TOL
        _gate(mesh, plan)


class TestSteppedChamfered:
    """Stepped plate with a Ø6 through bore and two 2x45° chamfers."""

    def test_corpus_and_core(self):
        name = "corpus_stepped_chamfered.stl"
        mesh = _load(name)
        _check_fixture_volume(name, mesh)
        report, feats, plan = _full(mesh)
        assert report.coverage >= 0.999
        holes = feats.by_kind("hole")
        assert len(holes) == 1
        assert abs(holes[0].params["diameter"] - 6.0) <= SIZE_TOL
        assert holes[0].params["through"] is True
        chams = feats.by_kind("chamfer")
        assert len(chams) == 2
        for c in chams:
            assert abs(c.params["size"] - 2.0) <= SIZE_TOL
            assert abs(c.params["angle_deg"] - 45.0) <= 2.0
        assert len(plan.pockets) >= 3, "stepped plate lost its steps"
        _gate(mesh, plan)
